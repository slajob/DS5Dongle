#!/usr/bin/env python3
"""Regenerate src/hid_report_descriptors.inc from the DS5Dongle firmware.

The virtual wired controller must present exactly the same HID report
descriptors as the Pico firmware (src/usb_descriptors.cpp in the repository
root), so they are extracted from there instead of being copied by hand.

Usage: python3 tools/gen_descriptors.py [path/to/usb_descriptors.cpp]
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
DEFAULT_SRC = HERE.parents[2] / "src" / "usb_descriptors.cpp"
OUT = HERE.parent / "src" / "hid_report_descriptors.inc"


def extract_array(source: str, name: str) -> list[int]:
    match = re.search(r"uint8_t const " + name + r"\[\] = \{(.*?)\n\};", source, re.S)
    if not match:
        raise SystemExit(f"array {name} not found")
    values: list[int] = []
    for line in match.group(1).split("\n"):
        code = line.split("//")[0]
        values += [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]{1,2}\b", code)]
    return values


def format_array(name: str, values: list[int]) -> str:
    lines = [f"static const uint8_t {name}[{len(values)}] = {{"]
    for i in range(0, len(values), 12):
        chunk = ", ".join(f"0x{v:02X}" for v in values[i:i + 12])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    src_path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SRC
    source = src_path.read_text()
    ds = extract_array(source, "desc_hid_report_ds")
    dse = extract_array(source, "desc_hid_report_dse")
    assert len(ds) == 321, len(ds)
    assert len(dse) == 437, len(dse)
    OUT.write_text(
        "// Generated by tools/gen_descriptors.py from the DS5Dongle firmware\n"
        "// (src/usb_descriptors.cpp). Do not edit by hand.\n\n"
        + format_array("kHidReportDescriptorDs", ds)
        + "\n\n"
        + format_array("kHidReportDescriptorDse", dse)
        + "\n"
    )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
